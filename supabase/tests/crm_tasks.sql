begin;
do $$
declare
  creator text := 'qa-task-creator-'||gen_random_uuid()::text;
  assignee text := 'qa-task-assignee-'||gen_random_uuid()::text;
  outsider text := 'qa-task-outsider-'||gen_random_uuid()::text;
  observer text := 'qa-task-observer-'||gen_random_uuid()::text;
  legacy uuid;
  second_observer text := 'qa-task-second-observer-'||gen_random_uuid()::text;
  task public.v2_tasks%rowtype;
  before_version int;
  denied boolean;
  summary jsonb;
begin
  insert into public.v2_employees(id,full_name,login,role)
  values(creator,'QA creator',creator,'manager'),(assignee,'QA assignee',assignee,'logist'),(outsider,'QA outsider',outsider,'manager'),(observer,'QA observer',observer,'cashier'),(second_observer,'QA second observer',second_observer,'senior_logist');
  denied:=false;
  begin perform public.v2_mutate_task(creator,'create',null,jsonb_build_object('title','Invalid observer','assigneeId',assignee,'observerId',outsider,'dueAt',now())); exception when others then denied:=true; end;
  if not denied then raise exception 'Manager accepted as observer'; end if;

  task:=public.v2_mutate_task(creator,'create',null,jsonb_build_object('title','QA task','assigneeId',assignee,'observerId',observer,'dueAt',now()-interval '1 hour','requiresReview',true,'target',jsonb_build_object('type','school','id','TIS','label','TIS','schoolKey','TIS')));
  if task.observer_id<>observer or task.status<>'new' or task.school_key<>'TIS' then raise exception 'New task defaults/context are incorrect'; end if;
  summary:=public.v2_task_summary(assignee);
  if (summary->>'new')::int<>1 or (summary->>'overdue')::int<>1 or (summary->>'attention')::int<>1 then raise exception 'Task attention counters are incorrect'; end if;
  denied:=false;
  begin perform public.v2_mutate_task(outsider,'comment',task.id,jsonb_build_object('version',task.version,'comment','forbidden')); exception when others then denied:=true; end;
  if not denied then raise exception 'Unrelated employee can mutate task'; end if;
  denied:=false;
  begin perform public.v2_mutate_task(creator,'accept',task.id,jsonb_build_object('version',task.version)); exception when others then denied:=true; end;
  if not denied then raise exception 'Creator accepted another employee task'; end if;
  if (public.v2_task_summary(observer)->>'watching')::int<>1 then raise exception 'Observer task not counted'; end if;
  denied:=false;
  begin perform public.v2_mutate_task(observer,'accept',task.id,jsonb_build_object('version',task.version)); exception when others then denied:=true; end;
  if not denied then raise exception 'Observer accepted task'; end if;
  denied:=false;
  begin perform public.v2_mutate_task(observer,'edit',task.id,jsonb_build_object('version',task.version,'assigneeId',outsider)); exception when others then denied:=true; end;
  if not denied then raise exception 'Observer edited task'; end if;
  task:=public.v2_mutate_task(observer,'comment',task.id,jsonb_build_object('version',task.version,'comment','Watching the route'));
  before_version:=task.version;
  task:=public.v2_mutate_task(assignee,'accept',task.id,jsonb_build_object('version',task.version));
  if task.status<>'in_progress' or task.accepted_at is null then raise exception 'Task not accepted'; end if;
  denied:=false;
  begin perform public.v2_mutate_task(assignee,'comment',task.id,jsonb_build_object('version',before_version,'comment','stale')); exception when others then denied:=true; end;
  if not denied then raise exception 'Stale edit was accepted'; end if;
  denied:=false;
  begin perform public.v2_mutate_task(assignee,'edit',task.id,jsonb_build_object('version',task.version,'dueAt',now()+interval '1 day')); exception when others then denied:=true; end;
  if not denied then raise exception 'Deadline changed without reason'; end if;
  task:=public.v2_mutate_task(assignee,'edit',task.id,jsonb_build_object('version',task.version,'title','Forbidden title','dueAt',now()+interval '1 day','comment','Waiting for route approval'));
  if task.title<>'QA task' then raise exception 'Assignee changed protected fields'; end if;
  denied:=false;
  begin perform public.v2_mutate_task(assignee,'submit',task.id,jsonb_build_object('version',task.version,'result','')); exception when others then denied:=true; end;
  if not denied then raise exception 'Task completed without result'; end if;
  task:=public.v2_mutate_task(assignee,'submit',task.id,jsonb_build_object('version',task.version,'result','Route checked'));
  if task.status<>'review' then raise exception 'Review was skipped'; end if;
  denied:=false;
  begin perform public.v2_mutate_task(assignee,'approve',task.id,jsonb_build_object('version',task.version)); exception when others then denied:=true; end;
  if not denied then raise exception 'Assignee approved own result'; end if;
  summary:=public.v2_task_summary(creator);
  if (summary->>'review')::int<>1 then raise exception 'Creator did not receive review notification'; end if;
  task:=public.v2_mutate_task(creator,'return',task.id,jsonb_build_object('version',task.version,'comment','Check stop 2'));
  task:=public.v2_mutate_task(assignee,'submit',task.id,jsonb_build_object('version',task.version,'result','Stop 2 checked'));
  task:=public.v2_mutate_task(creator,'approve',task.id,jsonb_build_object('version',task.version));
  if task.status<>'done' or task.completed_at is null then raise exception 'Approval did not close task'; end if;
  if (public.v2_task_summary(assignee)->>'attention')::int<>0 then raise exception 'Closed task remains in attention counter'; end if;
  task:=public.v2_mutate_task(creator,'reopen',task.id,jsonb_build_object('version',task.version,'comment','Recheck tomorrow'));
  task:=public.v2_mutate_task(creator,'edit',task.id,jsonb_build_object('version',task.version,'assigneeId',outsider));
  if task.status<>'new' or task.assignee_id<>outsider or task.accepted_at is not null then raise exception 'Reassignment did not require acceptance'; end if;
  task:=public.v2_mutate_task(creator,'edit',task.id,jsonb_build_object('version',task.version,'observerId',second_observer));
  if (public.v2_task_summary(observer)->>'watching')::int<>0 then raise exception 'Former observer still counted'; end if;
  denied:=false;
  begin perform public.v2_mutate_task(observer,'comment',task.id,jsonb_build_object('version',task.version,'comment','No longer observing')); exception when others then denied:=true; end;
  if not denied then raise exception 'Former observer retained access'; end if;
  task:=public.v2_mutate_task(second_observer,'comment',task.id,jsonb_build_object('version',task.version,'comment','New observer'));
  task:=public.v2_mutate_task(creator,'cancel',task.id,jsonb_build_object('version',task.version,'comment','QA complete'));
  if task.status<>'cancelled' then raise exception 'Task not cancelled'; end if;
  if (select count(*) from public.v2_task_events where task_id=task.id)<>13 then raise exception 'Task event history incomplete'; end if;
  insert into public.v2_tasks(title,creator_id,assignee_id,due_at) values('Legacy QA',creator,assignee,now()) returning id into legacy;
  denied:=false;
  begin perform public.v2_mutate_task(outsider,'comment',legacy,jsonb_build_object('version',1,'comment','forbidden')); exception when others then denied:=true; end;
  if not denied then raise exception 'NULL observer bypassed access control'; end if;
  if has_function_privilege('anon','public.v2_mutate_task(text,text,uuid,jsonb)','execute') or has_function_privilege('authenticated','public.v2_mutate_task(text,text,uuid,jsonb)','execute') then raise exception 'Browser can bypass signed employee-session API'; end if;
  if has_table_privilege('anon','public.v2_tasks','select') or has_table_privilege('authenticated','public.v2_tasks','update') then raise exception 'Tasks exposed directly'; end if;
end;
$$;
select 'PASS: lifecycle, authorization, acceptance, version conflicts, rescheduling reasons, results, review, reassignment, history, reminders, observer roles, observer revocation, legacy NULL observer denial' as result;
rollback;
